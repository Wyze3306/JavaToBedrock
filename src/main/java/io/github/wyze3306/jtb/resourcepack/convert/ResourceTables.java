package io.github.wyze3306.jtb.resourcepack.convert;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.jspecify.annotations.Nullable;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;

/**
 * Static tables of the converter, generated by {@code tools/gen_resourcepack_tables.py} into
 * {@code mappings/resourcepack/} (sources in {@code mappings/SOURCES.md}). Texture and flipbook paths
 * are relative to {@code textures/} without extension, sound paths relative to {@code sounds/}.
 */
public final class ResourceTables {

    /** A Java vanilla texture and the size of one of its frames (aspect-ratio check of overrides). */
    public record JavaTexture(String path, int width, int height) {
    }

    /** A Bedrock flipbook animation; null fields take the Bedrock defaults. */
    public record Flipbook(@Nullable Integer ticks, int @Nullable [] frames, @Nullable Boolean blend) {
    }

    /** A Java block usable as custom-block carrier: its properties in Java order and vanilla blockstate. */
    public record Carrier(String block, List<Property> properties, JsonObject blockstate) {
    }

    public record Property(String name, List<String> values) {
    }

    private static volatile @Nullable ResourceTables instance;

    /** Bedrock vanilla texture -> Java vanilla textures it can replace one to one. */
    private final Map<String, List<JavaTexture>> textures;
    /** Java texture -> Bedrock sources, preferred first (same file name, then alphabetical). */
    private final Map<String, List<String>> sourcesByTarget;
    private final Map<String, List<String>> terrainAtlas;
    private final Map<String, List<String>> itemAtlas;
    private final Map<String, Flipbook> flipbooks;
    private final Set<String> soundsSame;
    private final Map<String, List<String>> soundsMapped;
    private final Map<String, Carrier> carriers;

    private ResourceTables() {
        JsonObject textures = read("textures.json").getAsJsonObject();
        Map<String, List<JavaTexture>> byBedrock = new TreeMap<>();
        Map<String, List<String>> byTarget = new TreeMap<>();
        for (Map.Entry<String, JsonElement> entry : textures.entrySet()) {
            List<JavaTexture> targets = new ArrayList<>();
            for (JsonElement target : entry.getValue().getAsJsonArray()) {
                JsonArray t = target.getAsJsonArray();
                JavaTexture texture = new JavaTexture(t.get(0).getAsString(), t.get(1).getAsInt(), t.get(2).getAsInt());
                targets.add(texture);
                byTarget.computeIfAbsent(texture.path(), k -> new ArrayList<>()).add(entry.getKey());
            }
            byBedrock.put(entry.getKey(), List.copyOf(targets));
        }
        byTarget.replaceAll((target, sources) -> {
            String stem = target.substring(target.lastIndexOf('/') + 1);
            List<String> sorted = new ArrayList<>(sources);
            sorted.sort((a, b) -> {
                boolean sameA = a.substring(a.lastIndexOf('/') + 1).equals(stem);
                boolean sameB = b.substring(b.lastIndexOf('/') + 1).equals(stem);
                return sameA != sameB ? (sameA ? -1 : 1) : a.compareTo(b);
            });
            return List.copyOf(sorted);
        });
        this.textures = Collections.unmodifiableMap(byBedrock);
        this.sourcesByTarget = Collections.unmodifiableMap(byTarget);

        JsonObject atlases = read("atlases.json").getAsJsonObject();
        this.terrainAtlas = stringLists(atlases.getAsJsonObject("terrain"));
        this.itemAtlas = stringLists(atlases.getAsJsonObject("items"));

        Map<String, Flipbook> flipbooks = new HashMap<>();
        for (Map.Entry<String, JsonElement> entry : read("flipbooks.json").getAsJsonObject().entrySet()) {
            flipbooks.put(entry.getKey(), flipbook(entry.getValue().getAsJsonObject()));
        }
        this.flipbooks = Collections.unmodifiableMap(flipbooks);

        JsonObject sounds = read("sound_files.json").getAsJsonObject();
        Set<String> same = new HashSet<>();
        sounds.getAsJsonArray("same").forEach(e -> same.add(e.getAsString()));
        this.soundsSame = Collections.unmodifiableSet(same);
        this.soundsMapped = stringLists(sounds.getAsJsonObject("mapped"));

        Map<String, Carrier> carriers = new LinkedHashMap<>();
        for (Map.Entry<String, JsonElement> entry : read("carrier_blocks.json").getAsJsonObject().entrySet()) {
            JsonObject carrier = entry.getValue().getAsJsonObject();
            List<Property> properties = new ArrayList<>();
            for (JsonElement property : carrier.getAsJsonArray("properties")) {
                JsonArray p = property.getAsJsonArray();
                List<String> values = new ArrayList<>();
                p.get(1).getAsJsonArray().forEach(v -> values.add(v.getAsString()));
                properties.add(new Property(p.get(0).getAsString(), List.copyOf(values)));
            }
            carriers.put(entry.getKey(), new Carrier(entry.getKey(), List.copyOf(properties), carrier.getAsJsonObject("blockstate")));
        }
        this.carriers = Collections.unmodifiableMap(carriers);
    }

    public static ResourceTables get() {
        ResourceTables tables = instance;
        if (tables == null) {
            synchronized (ResourceTables.class) {
                tables = instance;
                if (tables == null) {
                    tables = new ResourceTables();
                    instance = tables;
                }
            }
        }
        return tables;
    }

    public Map<String, List<JavaTexture>> textures() {
        return this.textures;
    }

    /** Bedrock sources of a Java texture, preferred first. */
    public List<String> sources(String javaTexture) {
        return this.sourcesByTarget.getOrDefault(javaTexture, List.of());
    }

    public Map<String, List<String>> sourcesByTarget() {
        return this.sourcesByTarget;
    }

    /** Vanilla {@code terrain_texture.json} short names (with a mapped texture) -> texture paths. */
    public Map<String, List<String>> terrainAtlas() {
        return this.terrainAtlas;
    }

    /** Vanilla {@code item_texture.json} short names (with a mapped texture) -> texture paths. */
    public Map<String, List<String>> itemAtlas() {
        return this.itemAtlas;
    }

    /** Vanilla flipbooks by texture path. */
    public Map<String, Flipbook> flipbooks() {
        return this.flipbooks;
    }

    /** Java vanilla sound files ({@code sounds/} relative, no extension) a Bedrock vanilla sound file replaces. */
    public List<String> javaSoundFiles(String bedrockSound) {
        if (this.soundsSame.contains(bedrockSound)) {
            return List.of(bedrockSound);
        }
        return this.soundsMapped.getOrDefault(bedrockSound, List.of());
    }

    public @Nullable Carrier carrier(String javaBlock) {
        return this.carriers.get(javaBlock);
    }

    static Flipbook flipbook(JsonObject json) {
        Integer ticks = json.has("ticks") && json.get("ticks").isJsonPrimitive() ? json.get("ticks").getAsInt() : null;
        int[] frames = null;
        if (json.has("frames") && json.get("frames").isJsonArray()) {
            JsonArray array = json.getAsJsonArray("frames");
            frames = new int[array.size()];
            for (int i = 0; i < frames.length; i++) {
                frames[i] = array.get(i).isJsonPrimitive() ? array.get(i).getAsInt() : 0;
            }
        }
        Boolean blend = json.has("blend") && json.get("blend").isJsonPrimitive() ? json.get("blend").getAsBoolean() : null;
        return new Flipbook(ticks, frames, blend);
    }

    private static Map<String, List<String>> stringLists(JsonObject json) {
        Map<String, List<String>> out = new HashMap<>();
        for (Map.Entry<String, JsonElement> entry : json.entrySet()) {
            List<String> values = new ArrayList<>();
            entry.getValue().getAsJsonArray().forEach(v -> values.add(v.getAsString()));
            out.put(entry.getKey(), List.copyOf(values));
        }
        return Collections.unmodifiableMap(out);
    }

    private static JsonElement read(String name) {
        String path = "mappings/resourcepack/" + name;
        try (InputStream in = ResourceTables.class.getClassLoader().getResourceAsStream(path)) {
            if (in == null) {
                throw new IllegalStateException(path + " missing from the jar");
            }
            return JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8));
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}

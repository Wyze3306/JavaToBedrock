package io.github.wyze3306.jtb.entity;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.geysermc.mcprotocollib.protocol.data.game.entity.Effect;
import org.geysermc.mcprotocollib.protocol.data.game.entity.metadata.MetadataType;
import org.geysermc.mcprotocollib.protocol.data.game.entity.metadata.MetadataTypes;
import org.geysermc.mcprotocollib.protocol.data.game.entity.type.EntityType;
import org.jspecify.annotations.Nullable;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Static entity mapping data, loaded once at startup from {@code mappings/entity/entities.json}
 * (generated by {@code tools/gen_entity_mappings.py} from ViaBedrock and Geyser data): Bedrock entity
 * identifiers to Java 26.3 entity types, the entity data layout and hit box of every Java type, the
 * Bedrock position offsets, painting motives, effect ids and damage causes.
 * <p>
 * Read-only after {@link #load()}, safe from any thread.
 */
public final class EntityDefinitions {

    private static final String RESOURCE = "/mappings/entity/entities.json";

    private static volatile @Nullable Data data;

    private record Data(Map<String, JavaEntityDefinition> bedrock, Set<String> unmapped, JavaEntityDefinition[] java,
                        Map<String, String> paintings, Effect[] effects, String[] damageCauses, String[] boatVariants) {
    }

    private EntityDefinitions() {
    }

    /** Loads the tables (idempotent). */
    public static synchronized void load() {
        if (data != null) {
            return;
        }
        try (InputStream in = EntityDefinitions.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                throw new IllegalStateException("Missing resource " + RESOURCE);
            }
            data = parse(JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject());
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot read " + RESOURCE, e);
        }
    }

    private static Data data() {
        Data loaded = data;
        if (loaded == null) {
            load();
            loaded = data;
        }
        return loaded;
    }

    private static Data parse(JsonObject root) {
        JsonObject classes = root.getAsJsonObject("classes");
        JsonObject types = root.getAsJsonObject("java_types");
        JavaEntityDefinition[] java = new JavaEntityDefinition[EntityType.values().length];
        Map<String, JavaEntityDefinition> byJavaName = new HashMap<>();
        for (EntityType type : EntityType.values()) {
            String name = type.name().toLowerCase(Locale.ROOT);
            JsonObject entry = types.getAsJsonObject(name);
            if (entry == null) {
                throw new IllegalStateException("No entity mapping for Java type " + name);
            }
            List<String> names = new ArrayList<>();
            List<MetadataType<?>> metadataTypes = new ArrayList<>();
            collectFields(classes, entry.get("class").getAsString(), names, metadataTypes);
            float offset = entry.has("offset") ? entry.get("offset").getAsFloat() : 0;
            JavaEntityDefinition definition = new JavaEntityDefinition(type, entry.get("width").getAsFloat(),
                    entry.get("height").getAsFloat(), offset, names.toArray(String[]::new),
                    metadataTypes.toArray(MetadataType<?>[]::new));
            java[type.ordinal()] = definition;
            byJavaName.put(name, definition);
        }

        Map<String, JavaEntityDefinition> bedrock = new HashMap<>();
        Set<String> unmapped = new HashSet<>();
        for (Map.Entry<String, JsonElement> entry : root.getAsJsonObject("bedrock_to_java").entrySet()) {
            if (entry.getValue().isJsonNull()) {
                unmapped.add(entry.getKey());
            } else {
                bedrock.put(entry.getKey(), byJavaName.get(entry.getValue().getAsString()));
            }
        }

        Map<String, String> paintings = new HashMap<>();
        for (Map.Entry<String, JsonElement> entry : root.getAsJsonObject("paintings").entrySet()) {
            paintings.put(entry.getKey(), "minecraft:" + entry.getValue().getAsString());
        }

        JsonObject effectsJson = root.getAsJsonObject("effects");
        Effect[] effects = new Effect[effectsJson.size() + 1];
        for (Map.Entry<String, JsonElement> entry : effectsJson.entrySet()) {
            if (!entry.getValue().isJsonNull()) {
                effects[Integer.parseInt(entry.getKey())] = Effect.valueOf(entry.getValue().getAsString().toUpperCase(Locale.ROOT));
            }
        }

        return new Data(Collections.unmodifiableMap(bedrock), Collections.unmodifiableSet(unmapped), java,
                Collections.unmodifiableMap(paintings), effects, strings(root.getAsJsonArray("damage_causes"), "minecraft:"),
                strings(root.getAsJsonArray("boat_variants"), ""));
    }

    private static void collectFields(JsonObject classes, String name, List<String> names, List<MetadataType<?>> types) {
        JsonObject cls = classes.getAsJsonObject(name);
        if (cls == null) {
            throw new IllegalStateException("Unknown entity data class " + name);
        }
        JsonElement parent = cls.get("parent");
        if (parent != null && !parent.isJsonNull()) {
            collectFields(classes, parent.getAsString(), names, types);
        }
        for (JsonElement field : cls.getAsJsonArray("fields")) {
            JsonArray pair = field.getAsJsonArray();
            names.add(pair.get(0).getAsString());
            types.add(metadataType(pair.get(1).getAsString()));
        }
    }

    private static MetadataType<?> metadataType(String name) {
        try {
            return (MetadataType<?>) MetadataTypes.class.getField(name).get(null);
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException("Unknown metadata type " + name, e);
        }
    }

    private static String[] strings(JsonArray array, String prefix) {
        String[] out = new String[array.size()];
        for (int i = 0; i < out.length; i++) {
            out[i] = prefix + array.get(i).getAsString();
        }
        return out;
    }

    /**
     * The Java type a vanilla Bedrock identifier ({@code minecraft:zombie}) maps to, or null when it has
     * none (custom entities, or Bedrock-only ones such as {@code minecraft:agent}).
     */
    public static @Nullable JavaEntityDefinition forBedrock(String identifier) {
        return data().bedrock().get(identifier);
    }

    /** Vanilla Bedrock entities that have no Java counterpart and are not shown. */
    public static boolean isUnmappedVanilla(String identifier) {
        return data().unmapped().contains(identifier);
    }

    public static JavaEntityDefinition forJava(EntityType type) {
        return data().java()[type.ordinal()];
    }

    /** Java painting variant key ({@code minecraft:kebab}) of a Bedrock motive, or null. */
    public static @Nullable String paintingVariant(String motive) {
        return data().paintings().get(motive);
    }

    /** Java effect of a Bedrock effect id (1-based), or null when Java has no equivalent. */
    public static @Nullable Effect javaEffect(int bedrockEffectId) {
        Effect[] effects = data().effects();
        return bedrockEffectId > 0 && bedrockEffectId < effects.length ? effects[bedrockEffectId] : null;
    }

    /** Java damage type key of a Bedrock {@code ActorDamageCause} id ({@code minecraft:generic} when unknown). */
    public static String damageType(int bedrockCause) {
        String[] causes = data().damageCauses();
        return bedrockCause >= 0 && bedrockCause < causes.length ? causes[bedrockCause] : "minecraft:generic";
    }

    /** Wood name of a Bedrock boat {@code VARIANT} ({@code oak} when unknown). */
    public static String boatWood(int variant) {
        String[] woods = data().boatVariants();
        return variant >= 0 && variant < woods.length ? woods[variant] : woods[0];
    }
}

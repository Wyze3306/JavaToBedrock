package io.github.wyze3306.jtb.item;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import it.unimi.dsi.fastutil.ints.Int2IntMap;
import it.unimi.dsi.fastutil.ints.Int2IntOpenHashMap;
import it.unimi.dsi.fastutil.ints.Int2ObjectMap;
import it.unimi.dsi.fastutil.ints.Int2ObjectOpenHashMap;
import it.unimi.dsi.fastutil.objects.Object2IntMap;
import it.unimi.dsi.fastutil.objects.Object2IntOpenHashMap;
import net.kyori.adventure.key.Key;
import org.geysermc.mcprotocollib.protocol.data.game.entity.EquipmentSlot;
import org.jspecify.annotations.Nullable;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.zip.GZIPInputStream;

/**
 * The static item tables of {@code mappings/items/item_mappings.json.gz} (generated by
 * {@code tools/gen_item_mappings.py}): the Java 26.3 item registry with the default properties the
 * click simulation needs, every vanilla Bedrock item identifier/aux value as a Java item, and the
 * small Bedrock <-> Java id tables of item data (potions, enchantments, effects, banner patterns), and
 * the vanilla Bedrock item tags recipes refer to.
 * <p>
 * Loaded once (class initialisation, thread safe) and immutable afterwards.
 */
public final class ItemMappings {

    private static final String RESOURCE = "/mappings/items/item_mappings.json.gz";
    private static final int FLAG_FUEL = 1;
    private static final int FLAG_BREWING_FUEL = 2;

    /**
     * A Java item and its default components that matter to the proxy.
     *
     * @param equipSlot 0 none, 1 head, 2 chest, 3 legs, 4 feet, 5 body, 6 saddle
     */
    public record JavaItem(int id, Key key, int maxStackSize, int maxDamage, boolean fuel, boolean brewingFuel, int equipSlot) {

        /** The armour slot this item is worn in, or null. */
        public @Nullable EquipmentSlot armorSlot() {
            return switch (this.equipSlot) {
                case 1 -> EquipmentSlot.HELMET;
                case 2 -> EquipmentSlot.CHESTPLATE;
                case 3 -> EquipmentSlot.LEGGINGS;
                case 4 -> EquipmentSlot.BOOTS;
                default -> null;
            };
        }
    }

    /** A custom potion effect of a Bedrock potion that has no Java potion type (e.g. strong wither). */
    public record EffectSpec(Key effect, int amplifier, int duration) {
    }

    /**
     * How a Bedrock item (identifier and aux value) appears on Java.
     *
     * @param nameKey     a Bedrock translation key used as the Java item name when the Java item is only
     *                    an approximation (double slabs, education items...), else null
     * @param potion      Java potion key ({@code minecraft:water}...) for potions and tipped arrows
     * @param blockState  Java block state properties (cake bites, light level)
     * @param instrument  Java instrument key for goat horns
     * @param effects     custom effects for potions without a Java potion type
     * @param color       custom potion colour (RGB) for {@code effects}, or -1
     */
    public record Mapping(int javaId, @Nullable String nameKey, @Nullable Key potion, @Nullable Map<String, String> blockState,
                          @Nullable Key instrument, @Nullable List<EffectSpec> effects, int color) {
    }

    /** A Bedrock item that a Java item comes from: {@code aux} is -1 for the identifier's default entry. */
    public record BedrockVariant(String identifier, int aux, Mapping mapping) {
    }

    private static final ItemMappings INSTANCE = load();

    private final JavaItem[] javaItems;
    private final Map<Key, JavaItem> javaItemsByKey;
    private final Map<String, Int2ObjectMap<Mapping>> bedrockItems;
    private final Map<String, Mapping> bedrockDefaults;
    private final Int2ObjectMap<List<BedrockVariant>> javaToBedrock;
    private final List<Key> potions;
    private final Object2IntMap<Key> potionIds;
    private final Int2ObjectMap<Key> enchantments;
    private final Object2IntMap<Key> bedrockEnchantments;
    private final Int2IntMap effects;
    private final Int2IntMap bedrockEffects;
    private final Map<String, Key> bannerPatterns;
    private final Map<Key, String> bedrockBannerPatterns;
    private final Map<String, Set<String>> itemTags;

    private ItemMappings(JsonObject root) {
        JsonArray items = root.getAsJsonArray("java_items");
        this.javaItems = new JavaItem[items.size()];
        Map<Key, JavaItem> byKey = new HashMap<>(items.size() * 2);
        for (int i = 0; i < items.size(); i++) {
            JsonArray entry = items.get(i).getAsJsonArray();
            int flags = entry.get(3).getAsInt();
            JavaItem item = new JavaItem(i, Key.key(entry.get(0).getAsString()), entry.get(1).getAsInt(),
                    entry.get(2).getAsInt(), (flags & FLAG_FUEL) != 0, (flags & FLAG_BREWING_FUEL) != 0, (flags >> 4) & 0xF);
            this.javaItems[i] = item;
            byKey.put(item.key(), item);
        }
        this.javaItemsByKey = Collections.unmodifiableMap(byKey);

        JsonArray potionList = root.getAsJsonArray("potions");
        List<Key> potionKeys = new ArrayList<>(potionList.size());
        this.potionIds = new Object2IntOpenHashMap<>();
        this.potionIds.defaultReturnValue(-1);
        for (JsonElement potion : potionList) {
            Key key = Key.key(potion.getAsString());
            this.potionIds.put(key, potionKeys.size());
            potionKeys.add(key);
        }
        this.potions = List.copyOf(potionKeys);

        JsonObject bedrock = root.getAsJsonObject("bedrock_items");
        this.bedrockItems = new HashMap<>(bedrock.size() * 2);
        this.bedrockDefaults = new HashMap<>(bedrock.size() * 2);
        this.javaToBedrock = new Int2ObjectOpenHashMap<>();
        for (Map.Entry<String, JsonElement> item : bedrock.entrySet()) {
            Int2ObjectMap<Mapping> byAux = new Int2ObjectOpenHashMap<>();
            for (Map.Entry<String, JsonElement> variant : item.getValue().getAsJsonObject().entrySet()) {
                Mapping mapping = parseMapping(variant.getValue().getAsJsonArray());
                int aux = variant.getKey().isEmpty() ? -1 : Integer.parseInt(variant.getKey());
                if (aux < 0) {
                    this.bedrockDefaults.put(item.getKey(), mapping);
                } else {
                    byAux.put(aux, mapping);
                }
                this.javaToBedrock.computeIfAbsent(mapping.javaId(), k -> new ArrayList<>())
                        .add(new BedrockVariant(item.getKey(), aux, mapping));
            }
            if (!byAux.isEmpty()) {
                this.bedrockItems.put(item.getKey(), byAux);
            }
        }
        // Exact equivalents first: an entry without a substitute name, with an explicit aux value.
        for (List<BedrockVariant> variants : this.javaToBedrock.values()) {
            variants.sort((a, b) -> Integer.compare(rank(a), rank(b)));
        }

        this.enchantments = new Int2ObjectOpenHashMap<>();
        this.bedrockEnchantments = new Object2IntOpenHashMap<>();
        this.bedrockEnchantments.defaultReturnValue(-1);
        for (Map.Entry<String, JsonElement> entry : root.getAsJsonObject("enchantments").entrySet()) {
            Key key = Key.key(entry.getValue().getAsString());
            int id = Integer.parseInt(entry.getKey());
            this.enchantments.put(id, key);
            this.bedrockEnchantments.put(key, id);
        }

        this.effects = new Int2IntOpenHashMap();
        this.effects.defaultReturnValue(-1);
        this.bedrockEffects = new Int2IntOpenHashMap();
        this.bedrockEffects.defaultReturnValue(-1);
        for (Map.Entry<String, JsonElement> entry : root.getAsJsonObject("effects").entrySet()) {
            int bedrockId = Integer.parseInt(entry.getKey());
            int javaId = entry.getValue().getAsInt();
            this.effects.put(bedrockId, javaId);
            this.bedrockEffects.putIfAbsent(javaId, bedrockId);
        }

        this.bannerPatterns = new HashMap<>();
        this.bedrockBannerPatterns = new HashMap<>();
        for (Map.Entry<String, JsonElement> entry : root.getAsJsonObject("banner_patterns").entrySet()) {
            Key key = Key.key(entry.getValue().getAsString());
            this.bannerPatterns.put(entry.getKey(), key);
            this.bedrockBannerPatterns.putIfAbsent(key, entry.getKey());
        }

        Map<String, Set<String>> tags = new HashMap<>();
        for (Map.Entry<String, JsonElement> entry : root.getAsJsonObject("item_tags").entrySet()) {
            List<String> members = new ArrayList<>();
            for (JsonElement item : entry.getValue().getAsJsonArray()) {
                members.add(item.getAsString());
            }
            tags.put(entry.getKey(), Set.copyOf(members));
        }
        this.itemTags = Collections.unmodifiableMap(tags);
    }

    private static int rank(BedrockVariant variant) {
        Mapping mapping = variant.mapping();
        int rank = mapping.nameKey() == null ? 0 : 4;
        if (variant.identifier().contains(":item.")) {
            rank += 2;
        }
        return rank + (variant.aux() < 0 ? 1 : 0);
    }

    private static Mapping parseMapping(JsonArray entry) {
        int javaId = entry.get(0).getAsInt();
        String nameKey = entry.get(1).isJsonNull() ? null : entry.get(1).getAsString();
        Key potion = null;
        Key instrument = null;
        Map<String, String> blockState = null;
        List<EffectSpec> effects = null;
        int color = -1;
        if (!entry.get(2).isJsonNull()) {
            JsonObject extra = entry.get(2).getAsJsonObject();
            if (extra.has("potion")) {
                potion = Key.key(extra.get("potion").getAsString());
            }
            if (extra.has("instrument")) {
                instrument = Key.key(extra.get("instrument").getAsString());
            }
            if (extra.has("block_state")) {
                Map<String, String> properties = new LinkedHashMap<>();
                for (Map.Entry<String, JsonElement> property : extra.getAsJsonObject("block_state").entrySet()) {
                    properties.put(property.getKey(), property.getValue().getAsString());
                }
                blockState = Collections.unmodifiableMap(properties);
            }
            if (extra.has("effects")) {
                List<EffectSpec> list = new ArrayList<>();
                for (JsonElement effect : extra.getAsJsonArray("effects")) {
                    JsonArray spec = effect.getAsJsonArray();
                    list.add(new EffectSpec(Key.key(spec.get(0).getAsString()), spec.get(1).getAsInt(), spec.get(2).getAsInt()));
                }
                effects = List.copyOf(list);
                color = extra.get("color").getAsInt();
            }
        }
        return new Mapping(javaId, nameKey, potion, blockState, instrument, effects, color);
    }

    private static ItemMappings load() {
        try (InputStream in = ItemMappings.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                throw new IllegalStateException("Missing resource " + RESOURCE);
            }
            try (InputStreamReader reader = new InputStreamReader(new GZIPInputStream(in), StandardCharsets.UTF_8)) {
                return new ItemMappings(JsonParser.parseReader(reader).getAsJsonObject());
            }
        } catch (IOException e) {
            throw new UncheckedIOException("Could not load " + RESOURCE, e);
        }
    }

    /** The mapping data, loaded once from the resources. */
    public static ItemMappings get() {
        return INSTANCE;
    }

    // ------------------------------------------------------------------ Java items

    /** Number of Java items (the registry size). */
    public int javaItemCount() {
        return this.javaItems.length;
    }

    /** The Java item with this registry id, or air for an unknown id. */
    public JavaItem javaItem(int id) {
        return id >= 0 && id < this.javaItems.length ? this.javaItems[id] : this.javaItems[0];
    }

    /** The Java item with this key, or null. */
    public @Nullable JavaItem javaItem(Key key) {
        return this.javaItemsByKey.get(key);
    }

    /** Java item id of {@code minecraft:<path>}; throws if it does not exist (static, known names only). */
    public int javaId(String path) {
        JavaItem item = this.javaItemsByKey.get(Key.key(path));
        if (item == null) {
            throw new IllegalArgumentException("Unknown Java item " + path);
        }
        return item.id();
    }

    // ------------------------------------------------------------------ Bedrock items

    /**
     * The Java form of a vanilla Bedrock item, or null when the identifier is not a vanilla item (a
     * custom item of the server). Unknown aux values use the identifier's default entry.
     */
    public @Nullable Mapping bedrock(String identifier, int aux) {
        Int2ObjectMap<Mapping> byAux = this.bedrockItems.get(identifier);
        if (byAux != null) {
            Mapping mapping = byAux.get(aux);
            if (mapping != null) {
                return mapping;
            }
        }
        return this.bedrockDefaults.get(identifier);
    }

    /** Bedrock items translated to this Java item, best (exact) equivalents first. */
    public List<BedrockVariant> bedrockVariants(int javaId) {
        List<BedrockVariant> variants = this.javaToBedrock.get(javaId);
        return variants == null ? List.of() : variants;
    }

    // ------------------------------------------------------------------ id tables

    /** Java potion registry id, or -1. */
    public int potionId(Key potion) {
        return this.potionIds.getInt(potion);
    }

    /** Java potion key of a potion registry id, or null. */
    public @Nullable Key potion(int id) {
        return id >= 0 && id < this.potions.size() ? this.potions.get(id) : null;
    }

    /** Java enchantment key of a Bedrock enchantment id, or null. */
    public @Nullable Key javaEnchantment(int bedrockId) {
        return this.enchantments.get(bedrockId);
    }

    /** Bedrock enchantment id of a Java enchantment key, or -1. */
    public int bedrockEnchantment(Key javaKey) {
        return this.bedrockEnchantments.getInt(javaKey);
    }

    /** Java mob effect id (MCProtocolLib {@code Effect} ordinal) of a Bedrock effect id, or -1. */
    public int javaEffect(int bedrockId) {
        return this.effects.get(bedrockId);
    }

    /** Bedrock effect id of a Java mob effect id, or -1. */
    public int bedrockEffect(int javaId) {
        return this.bedrockEffects.get(javaId);
    }

    /** Java banner pattern key of a Bedrock pattern code ({@code bs}, {@code cre}...), or null. */
    public @Nullable Key javaBannerPattern(String code) {
        return this.bannerPatterns.get(code);
    }

    /** Bedrock pattern code of a Java banner pattern key, or null. */
    public @Nullable String bedrockBannerPattern(Key javaKey) {
        return this.bedrockBannerPatterns.get(javaKey);
    }

    /** The vanilla Bedrock items with this tag (empty for an unknown tag). */
    public Set<String> tagItems(String tag) {
        return this.itemTags.getOrDefault(tag, Set.of());
    }

    /** Whether a vanilla Bedrock item has a vanilla item tag ({@code minecraft:planks}...). */
    public boolean hasTag(String identifier, String tag) {
        Set<String> items = this.itemTags.get(tag);
        return items != null && items.contains(identifier);
    }
}

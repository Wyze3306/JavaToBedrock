/**
 * The static Bedrock -> Java tables of the sound subsystem, loaded once from
 * {@code mappings/sound/*.json} (generated by {@code tools/gen_sound_mappings.py}): Bedrock sound names,
 * LevelSoundEvents, block sound types, note block instruments, particle effects and level events.
 * Immutable after {@link #load()}; safe to read from any thread.
 */
public final class SoundMappings {

    private static final Logger LOGGER = LoggerFactory.getLogger(SoundMappings.class);
    private static final String ROOT = "/mappings/sound/";

    /** One way a LevelSoundEvent sounds: the Java sound and its random volume and pitch ranges. */
    public record Variant(JavaSound sound, float minVolume, float maxVolume, float minPitch, float maxPitch) {

        public float volume() {
            return random(this.minVolume, this.maxVolume);
        }

        public float pitch() {
            return random(this.minPitch, this.maxPitch);
        }

        /** The same sound one octave-ish higher, as Bedrock plays baby mobs (+0.5 pitch). */
        public Variant baby() {
            return new Variant(this.sound, this.minVolume, this.maxVolume, this.minPitch + 0.5f, this.maxPitch + 0.5f);
        }

        private static float random(float min, float max) {
            return min >= max ? min : min + ThreadLocalRandom.current().nextFloat() * (max - min);
        }
    }

    /**
     * The variants of one LevelSoundEvent, looked up like the Bedrock client does: entity specific, then by the
     * sound type of the block in {@code data}, then generic.
     */
    public record LevelSound(@Nullable Variant generic, Map<String, Variant> entities, Map<String, Variant> blocks) {
    }

    /** What a Bedrock level event becomes on Java. */
    public sealed interface LevelEventMapping permits JavaLevelEvent, SoundLevelEvent, ParticleLevelEvent {
    }

    /** A Java level event; {@code data} replaces the Bedrock data when {@code fixedData}. */
    public record JavaLevelEvent(int id, boolean fixedData, int data) implements LevelEventMapping {
    }

    /** A sound; Bedrock events with data 0 play {@code withoutData} instead when set (dispenser clicks...). */
    public record SoundLevelEvent(JavaSound sound, @Nullable JavaLevelEvent withoutData) implements LevelEventMapping {
    }

    /** Particles. */
    public record ParticleLevelEvent(ParticleSpec particle) implements LevelEventMapping {
    }

    private static volatile boolean loaded;
    private static Map<String, JavaSound> sounds;
    private static Map<String, LevelSound> soundEvents;
    private static Map<SoundEvent, LevelSound> soundEventsByEnum;
    private static Map<String, String> blockSounds;
    private static JavaSound[] noteInstruments;
    private static Map<String, ParticleSpec> particleEffects;
    private static Int2ObjectMap<ParticleSpec> particlesById;
    private static Map<org.cloudburstmc.protocol.bedrock.data.ParticleType, ParticleSpec> particlesByType;
    private static Int2ObjectMap<LevelEventMapping> levelEventsById;
    private static Map<LevelEvent, LevelEventMapping> levelEvents;

    private SoundMappings() {
    }

    /** Loads every table (idempotent). Fails fast on a malformed or inconsistent resource. */
    public static synchronized void load() {
        if (loaded) {
            return;
        }
        long start = System.nanoTime();
        Map<String, BuiltinSound> builtin = new HashMap<>(BuiltinSound.values().length * 2);
        for (BuiltinSound sound : BuiltinSound.values()) {
            builtin.put(sound.getName(), sound);
        }

        JsonObject soundsJson = read("sounds.json").getAsJsonObject("sounds");
        Map<String, JavaSound> loadedSounds = new HashMap<>(soundsJson.size() * 2);
        for (Map.Entry<String, JsonElement> entry : soundsJson.entrySet()) {
            JsonArray value = entry.getValue().getAsJsonArray();
            BuiltinSound sound = builtin.get(value.get(0).getAsString());
            if (sound == null) {
                throw new IllegalStateException("Unknown Java sound " + value.get(0) + " for " + entry.getKey());
            }
            loadedSounds.put(entry.getKey(), JavaSound.builtin(sound, category(value.get(1).getAsString())));
        }
        sounds = Collections.unmodifiableMap(loadedSounds);

        JsonObject eventsRoot = read("sound_events.json");
        Map<String, LevelSound> loadedEvents = new HashMap<>();
        for (Map.Entry<String, JsonElement> entry : eventsRoot.getAsJsonObject("events").entrySet()) {
            Variant generic = null;
            Map<String, Variant> entities = new HashMap<>();
            Map<String, Variant> blocks = new HashMap<>();
            for (Map.Entry<String, JsonElement> variant : entry.getValue().getAsJsonObject().entrySet()) {
                Variant parsed = variant(variant.getValue().getAsJsonArray());
                String key = variant.getKey();
                if (key.isEmpty()) {
                    generic = parsed;
                } else if (key.startsWith("e:")) {
                    entities.put(key.substring(2), parsed);
                } else if (key.startsWith("b:")) {
                    blocks.put(key.substring(2), parsed);
                } else {
                    throw new IllegalStateException("Unknown level sound variant " + key);
                }
            }
            loadedEvents.put(entry.getKey(), new LevelSound(generic, Map.copyOf(entities), Map.copyOf(blocks)));
        }
        soundEvents = Collections.unmodifiableMap(loadedEvents);
        Map<SoundEvent, LevelSound> byEnum = new EnumMap<>(SoundEvent.class);
        for (SoundEvent event : SoundEvent.values()) {
            LevelSound sound = loadedEvents.get(event.getId());
            if (sound != null) {
                byEnum.put(event, sound);
            }
        }
        soundEventsByEnum = Collections.unmodifiableMap(byEnum);

        Map<String, String> loadedBlockSounds = new HashMap<>();
        for (Map.Entry<String, JsonElement> entry : eventsRoot.getAsJsonObject("block_sounds").entrySet()) {
            loadedBlockSounds.put(entry.getKey(), entry.getValue().getAsString().intern());
        }
        blockSounds = Collections.unmodifiableMap(loadedBlockSounds);
        JsonArray instruments = eventsRoot.getAsJsonArray("note_instruments");
        noteInstruments = new JavaSound[instruments.size()];
        for (int i = 0; i < noteInstruments.length; i++) {
            noteInstruments[i] = requireSound(instruments.get(i).getAsString());
        }

        JsonObject particlesRoot = read("particles.json");
        Map<String, ParticleSpec> effects = new HashMap<>();
        for (Map.Entry<String, JsonElement> entry : particlesRoot.getAsJsonObject("effects").entrySet()) {
            ParticleSpec spec = particle(entry.getValue().getAsJsonObject());
            if (!spec.isComplete()) {
                throw new IllegalStateException("Particle effect " + entry.getKey() + " is not writable: " + spec);
            }
            effects.put(entry.getKey(), spec);
        }
        particleEffects = Collections.unmodifiableMap(effects);
        Int2ObjectMap<ParticleSpec> byId = new Int2ObjectOpenHashMap<>();
        for (Map.Entry<String, JsonElement> entry : particlesRoot.getAsJsonObject("level_event_particles").entrySet()) {
            byId.put(Integer.parseInt(entry.getKey()), particle(entry.getValue().getAsJsonObject()));
        }
        particlesById = byId;
        Map<org.cloudburstmc.protocol.bedrock.data.ParticleType, ParticleSpec> byType =
                new EnumMap<>(org.cloudburstmc.protocol.bedrock.data.ParticleType.class);
        BedrockIds.particleTypes().forEach((id, type) -> {
            ParticleSpec spec = byId.get((int) id);
            if (spec != null) {
                byType.put(type, spec);
            }
        });
        particlesByType = Collections.unmodifiableMap(byType);

        Int2ObjectMap<LevelEventMapping> eventsById = new Int2ObjectOpenHashMap<>();
        for (Map.Entry<String, JsonElement> entry : read("level_events.json").getAsJsonObject("events").entrySet()) {
            eventsById.put(Integer.parseInt(entry.getKey()), levelEvent(entry.getValue().getAsJsonObject()));
        }
        levelEventsById = eventsById;
        Map<LevelEvent, LevelEventMapping> byEvent = new EnumMap<>(LevelEvent.class);
        BedrockIds.levelEvents().forEach((id, type) -> {
            LevelEventMapping mapping = eventsById.get((int) id);
            if (mapping != null && type instanceof LevelEvent event) {
                byEvent.put(event, mapping);
            }
        });
        levelEvents = Collections.unmodifiableMap(byEvent);

        loaded = true;
        LOGGER.info("Sound mappings: {} sounds, {} level sound events, {} particle effects, {} level events ({} ms)",
                sounds.size(), soundEvents.size(), particleEffects.size(), levelEvents.size(),
                (System.nanoTime() - start) / 1_000_000);
    }

    // ------------------------------------------------------------------ lookups

    /** The Java sound of a vanilla Bedrock sound name ({@code random.click}), or null for resource pack sounds. */
    public static @Nullable JavaSound vanillaSound(String bedrockName) {
        JavaSound sound = sounds.get(bedrockName);
        if (sound == null && !bedrockName.isEmpty()) {
            sound = sounds.get(bedrockName.toLowerCase(Locale.ROOT));
        }
        return sound;
    }

    /** Variants of a LevelSoundEvent (decoded enum), or null when it plays nothing on Java. */
    public static @Nullable LevelSound levelSound(SoundEvent event) {
        return soundEventsByEnum.get(event);
    }

    /** Variants of a LevelSoundEvent by its wire string, or null. */
    public static @Nullable LevelSound levelSound(String event) {
        return soundEvents.get(event);
    }

    /** Bedrock block sound type ({@code wood}, {@code stone}...) of a block identifier, or null. */
    public static @Nullable String blockSoundType(String bedrockBlock) {
        return blockSounds.get(bedrockBlock);
    }

    /** Sound of a Bedrock note block instrument id ({@code LevelSoundEvent note} data >> 8), or null. */
    public static @Nullable JavaSound noteInstrument(int instrument) {
        return instrument >= 0 && instrument < noteInstruments.length ? noteInstruments[instrument] : null;
    }

    /** Java particle of a {@code SpawnParticleEffect} identifier, or null for unknown (resource pack) effects. */
    public static @Nullable ParticleSpec particleEffect(String identifier) {
        return particleEffects.get(identifier);
    }

    /** Java particle of a Bedrock particle type (level event particles). May need its data from the event. */
    public static @Nullable ParticleSpec levelEventParticle(org.cloudburstmc.protocol.bedrock.data.ParticleType type) {
        return particlesByType.get(type);
    }

    /** Java particle of a Bedrock particle type by wire id ({@code ParticleGenericSpawn} data), or null. */
    public static @Nullable ParticleSpec levelEventParticle(int particleTypeId) {
        return particlesById.get(particleTypeId);
    }

    /** Java translation of a Bedrock level event, or null when it is handled in code or has no Java equivalent. */
    public static @Nullable LevelEventMapping levelEvent(LevelEvent event) {
        return levelEvents.get(event);
    }

    static Map<String, JavaSound> sounds() {
        return sounds;
    }

    static Map<String, LevelSound> soundEvents() {
        return soundEvents;
    }

    static Map<String, ParticleSpec> particleEffects() {
        return particleEffects;
    }

    static Int2ObjectMap<ParticleSpec> levelEventParticles() {
        return particlesById;
    }

    static Int2ObjectMap<LevelEventMapping> levelEventsById() {
        return levelEventsById;
    }

    // ------------------------------------------------------------------ parsing

    private static JsonObject read(String file) {
        try (InputStream in = SoundMappings.class.getResourceAsStream(ROOT + file)) {
            if (in == null) {
                throw new IllegalStateException("Missing resource " + ROOT + file);
            }
            try (Reader reader = new InputStreamReader(in, StandardCharsets.UTF_8)) {
                return JsonParser.parseReader(reader).getAsJsonObject();
            }
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot read " + ROOT + file, e);
        }
    }

    private static SoundCategory category(String name) {
        return SoundCategory.valueOf(name.toUpperCase(Locale.ROOT));
    }

    private static JavaSound requireSound(String bedrockName) {
        JavaSound sound = sounds.get(bedrockName);
        if (sound == null) {
            throw new IllegalStateException("Unknown Bedrock sound " + bedrockName);
        }
        return sound;
    }

    private static Variant variant(JsonArray value) {
        return new Variant(requireSound(value.get(0).getAsString()), value.get(1).getAsFloat(), value.get(2).getAsFloat(),
                value.get(3).getAsFloat(), value.get(4).getAsFloat());
    }

    private static ParticleSpec particle(JsonObject value) {
        ParticleType type = ParticleType.valueOf(value.get("type").getAsString());
        ParticleData data = value.has("data") ? particleData(value.getAsJsonObject("data")) : null;
        ParticleSpec spec = new ParticleSpec(type, data, number(value, "ox"), number(value, "oy"), number(value, "oz"),
                number(value, "speed"), value.has("count") ? value.get("count").getAsInt() : 0);
        if (ParticleSpec.UNWRITABLE.contains(type) || (data != null && !spec.isComplete())) {
            throw new IllegalStateException("Particle mapping cannot be written: " + value);
        }
        return spec;
    }

    private static float number(JsonObject value, String key) {
        return value.has(key) ? value.get(key).getAsFloat() : 0f;
    }

    private static ParticleData particleData(JsonObject data) {
        Map.Entry<String, JsonElement> entry = data.entrySet().iterator().next();
        JsonElement value = entry.getValue();
        return switch (entry.getKey()) {
            case "block" -> new BlockParticleData(value.getAsInt());
            case "color" -> new ColorParticleData(value.getAsInt());
            case "dust" -> new DustParticleData(value.getAsJsonArray().get(0).getAsInt(), value.getAsJsonArray().get(1).getAsFloat());
            case "transition" -> new DustColorTransitionParticleData(value.getAsJsonArray().get(0).getAsInt(),
                    value.getAsJsonArray().get(2).getAsFloat(), value.getAsJsonArray().get(1).getAsInt());
            case "item" -> new ItemParticleData(new ItemStack(value.getAsInt(), 1));
            case "shriek" -> new ShriekParticleData(value.getAsInt());
            case "roll" -> new SculkChargeParticleData(value.getAsFloat());
            // The target is relative to the emitter and filled in when the particle is sent.
            case "trail" -> new TrailParticleData(Vector3d.ZERO, value.getAsJsonArray().get(0).getAsInt(),
                    value.getAsJsonArray().get(1).getAsInt());
            default -> throw new IllegalStateException("Unknown particle data " + data);
        };
    }

    private static LevelEventMapping levelEvent(JsonObject value) {
        if (value.has("particle")) {
            return new ParticleLevelEvent(particle(value.getAsJsonObject("particle")));
        }
        JavaLevelEvent event = value.has("event")
                ? new JavaLevelEvent(value.get("event").getAsInt(), value.has("data"), value.has("data") ? value.get("data").getAsInt() : 0)
                : null;
        if (value.has("sound")) {
            return new SoundLevelEvent(requireSound(value.get("sound").getAsString()), event);
        }
        if (event == null) {
            throw new IllegalStateException("Empty level event mapping " + value);
        }
        return event;
    }
}

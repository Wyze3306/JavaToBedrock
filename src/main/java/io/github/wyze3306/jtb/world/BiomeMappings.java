package io.github.wyze3306.jtb.world;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import io.github.wyze3306.jtb.mapping.JavaRegistries;
import net.kyori.adventure.key.Key;
import org.jspecify.annotations.Nullable;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/**
 * Vanilla Bedrock biome ids (as chunks carry them) to the vanilla Java 26.3 biome registry, from
 * {@code mappings/world/biomes.json} (generated by {@code tools/gen_world_mappings.py}: Geyser's
 * table inverted, legacy Bedrock-only biomes mapped to their closest Java biome). Custom biomes of a
 * server are added per session by {@link WorldBiomes}.
 */
public final class BiomeMappings {

    private static final String RESOURCE = "mappings/world/biomes.json";

    private static int[] javaByBedrockId = new int[0];
    private static String[] nameByBedrockId = new String[0];
    private static final Map<String, Integer> bedrockIdByName = new HashMap<>();
    private static int plains;

    private BiomeMappings() {
    }

    /** Loads the table once (after {@link JavaRegistries}). */
    public static synchronized void load() {
        if (javaByBedrockId.length > 0) {
            return;
        }
        JsonObject root;
        try (InputStream in = BiomeMappings.class.getClassLoader().getResourceAsStream(RESOURCE)) {
            if (in == null) {
                throw new IOException(RESOURCE + " missing from the jar");
            }
            root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot load the biome table", e);
        }
        JavaRegistries.Registry registry = JavaRegistries.registry("minecraft:worldgen/biome");
        plains = registry.id("minecraft:plains");
        JsonObject ids = root.getAsJsonObject("bedrock_ids");
        JsonObject java = root.getAsJsonObject("java");
        int max = ids.keySet().stream().mapToInt(Integer::parseInt).max().orElse(0);
        int[] table = new int[max + 1];
        String[] names = new String[max + 1];
        Arrays.fill(table, -1);
        for (String key : ids.keySet()) {
            int id = Integer.parseInt(key);
            String name = ids.get(key).getAsString();
            names[id] = name;
            bedrockIdByName.put(name, id);
            int javaId = registry.id(Key.key(java.get(name).getAsString()));
            table[id] = javaId >= 0 ? javaId : plains;
        }
        javaByBedrockId = table;
        nameByBedrockId = names;
    }

    /** Java biome registry id of a vanilla Bedrock biome id, or -1 when the id is not vanilla. */
    public static int javaBiome(int bedrockId) {
        return bedrockId >= 0 && bedrockId < javaByBedrockId.length ? javaByBedrockId[bedrockId] : -1;
    }

    /** Vanilla Bedrock biome id of a name with or without namespace ({@code minecraft:plains}, {@code plains}), or -1. */
    public static int bedrockId(String name) {
        Integer id = bedrockIdByName.get(name.startsWith("minecraft:") ? name.substring(10) : name);
        return id == null ? -1 : id;
    }

    /** Name (without namespace) of a vanilla Bedrock biome id, or null. */
    public static @Nullable String bedrockName(int bedrockId) {
        return bedrockId >= 0 && bedrockId < nameByBedrockId.length ? nameByBedrockId[bedrockId] : null;
    }

    /** Copy of the vanilla id table, index = Bedrock id. */
    static int[] table() {
        return javaByBedrockId.clone();
    }

    /** Java id of {@code minecraft:plains}, the fallback for unknown biomes. */
    public static int plains() {
        return plains;
    }
}
